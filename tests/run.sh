#!/bin/sh
set -eux

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
cd "$ROOT"

EXPECTED_VERSION=$(cat VERSION)
./build/ylang --version | grep -Fq "$EXPECTED_VERSION"
./build/ylang --help > build/help.out
grep -q 'ylang check' build/help.out
grep -q 'ylang debug' build/help.out
grep -Fq "YLang v${EXPECTED_VERSION} — compiled language toolchain" build/help.out
./build/ylang check examples/type-conversions.yl >/dev/null
./build/ylang build examples/type-conversions.yl -o build/test-type-conversions >/dev/null
./build/test-type-conversions > build/type-conversions.out
diff -u tests/expected-type-conversions.txt build/type-conversions.out

# String and character escapes must have the same byte semantics in generated C.
./build/ylang check tests/escape-parity.yl >/dev/null
./build/ylang build tests/escape-parity.yl -o build/test-escape-parity >/dev/null
./build/test-escape-parity > build/escape-parity.out
diff -u tests/expected-escape-parity.txt build/escape-parity.out

# C trigraph sequences must survive unchanged in plain strings and f-string text.
./build/ylang check tests/trigraph-parity.yl >/dev/null
./build/ylang emit-c tests/trigraph-parity.yl -o build/trigraph-parity-generated.c >/dev/null
grep -Fq '\?\?=' build/trigraph-parity-generated.c
./build/ylang build tests/trigraph-parity.yl -o build/test-trigraph-parity >/dev/null
./build/test-trigraph-parity > build/trigraph-parity.out
diff -u tests/expected-trigraph-parity.txt build/trigraph-parity.out

# F-strings use the same escape decoder and unknown-escape fallback.
cat > build/fstring-escape.yl <<'EOF'
function main() -> int {
    print(f"hex \x4142");
    print(f"unknown \q");
    print(f"brace \{x\}");
    return 0;
}
EOF
./build/ylang build build/fstring-escape.yl -o build/test-fstring-escape >/dev/null
./build/test-fstring-escape > build/fstring-escape.out
diff -u tests/expected-fstring-escapes.txt build/fstring-escape.out
if ./build/ylang check tests/invalid-to-int.yl > build/invalid-to-int.out 2>&1; then
    echo "FAIL: to_int accepted an int argument" >&2
    exit 1
fi
grep -q "to_int expects a float argument" build/invalid-to-int.out
./build/ylang emit-c examples/demo.yl -o build/demo-generated.c > build/emit-c.out
grep -Fq "Generated by YLang v${EXPECTED_VERSION}" build/demo-generated.c

bash -n tools/test-2.2-candidate.sh

# Debug metadata maps generated C statements back to their original YLang lines.
./build/ylang emit-c tests/debug-source-map.yl -o build/debug-source-map.c >/dev/null
grep -Fq '#line 2 "tests/debug-source-map.yl"' build/debug-source-map.c
grep -Fq '#line 4 "tests/debug-source-map.yl"' build/debug-source-map.c
./build/ylang build tests/debug-source-map.yl -o build/test-debug-source-map >/dev/null
[ "$(./build/test-debug-source-map)" = "42" ]

# Imported modules retain their original source path, including paths with spaces.
./build/ylang check tests/debug-source-map-import.yl >/dev/null
./build/ylang emit-c tests/debug-source-map-import.yl -o build/debug-source-map-import.c >/dev/null
grep -E -q '#line 2 ".*debug map lib[.]yl"' build/debug-source-map-import.c
./build/ylang build tests/debug-source-map-import.yl -o build/test-debug-source-map-import >/dev/null
[ "$(./build/test-debug-source-map-import)" = "42" ]

# Launch the native debugger against a source-mapped debug build and exit cleanly.
if command -v gdb >/dev/null 2>&1; then
    printf 'quit\n' | ./build/ylang debug tests/debug-source-map.yl -o build/debug-launch-test > build/debug-launch.out 2>&1
elif command -v lldb >/dev/null 2>&1; then
    printf 'quit\n' | ./build/ylang debug tests/debug-source-map.yl -o build/debug-launch-test > build/debug-launch.out 2>&1
else
    echo "SKIP: GDB/LLDB is not installed; install one to run debugger launch coverage."
fi
if [ -f build/debug-launch.out ]; then
    grep -Fq "Build succeeded: build/debug-launch-test" build/debug-launch.out
fi

if ./build/ylang check tests/await-type-error.yl > build/await-type-error.out 2>&1; then
    echo "FAIL: await accepted an integer instead of an http_task" >&2
    exit 1
fi
grep -q 'E2123' build/await-type-error.out

# HTTP integration runs its loopback server in-process to avoid background process leakage.
python3 tests/run_http_integration.py
python3 tests/benchmark-smoke.py
if ./build/ylang > build/no-args.out 2>&1; then
    echo "FAIL: ylang without arguments should return usage error" >&2
    exit 1
else
    usage_status=$?
    [ "$usage_status" -eq 64 ]
fi
if ./build/ylang fix tests/typo-print.yl > build/fix-missing-output.out 2>&1; then
    echo "FAIL: fix worked without an explicit output path" >&2
    exit 1
fi
grep -q 'requires -o' build/fix-missing-output.out

# Embedded NUL bytes must not silently truncate source parsing.
printf 'function main() -> int { return 0; }\000function main() -> int { return 1; }\n' > build/embedded-nul.yl
if ./build/ylang check build/embedded-nul.yl > build/embedded-nul.out 2>&1; then
    echo "FAIL: source containing an embedded NUL byte was accepted" >&2
    exit 1
fi
grep -q 'contains a NUL byte' build/embedded-nul.out

# Excessively nested expressions must fail with a parser diagnostic, not a crash.
{
    printf 'function main() -> int { return '
    depth=0
    while [ "$depth" -lt 1000 ]; do
        printf '('
        depth=$((depth + 1))
    done
    printf '0'
    while [ "$depth" -gt 0 ]; do
        printf ')'
        depth=$((depth - 1))
    done
    printf '; }\n'
} > build/deep-expression-nesting.yl
if ./build/ylang check build/deep-expression-nesting.yl > build/deep-expression-nesting.out 2>&1; then
    echo "FAIL: excessively nested expression was accepted" >&2
    exit 1
else
    nesting_status=$?
    if [ "$nesting_status" -ne 1 ]; then
        echo "FAIL: expected a parser diagnostic exit status of 1, got $nesting_status" >&2
        exit 1
    fi
fi
grep -q 'E1017' build/deep-expression-nesting.out

# print() must keep its own stable diagnostic code.
cat > build/empty-print.yl <<'EOF'
function main() -> int {
    print();
    return 0;
}
EOF
if ./build/ylang check build/empty-print.yl > build/empty-print.out 2>&1; then
    echo "FAIL: print() without values was accepted" >&2
    exit 1
fi
grep -q 'E1015' build/empty-print.out
grep -q 'print() needs at least one value' build/empty-print.out
if grep -qi 'segmentation fault' build/deep-expression-nesting.out; then
    echo "FAIL: deeply nested expression crashed the compiler" >&2
    exit 1
fi

# The canonical 3.0 function keyword is accepted while legacy 'function' remains compatible.
./build/ylang check tests/fn-keyword.yl >/dev/null
./build/ylang build tests/fn-keyword.yl -o build/test-fn-keyword >/dev/null
./build/test-fn-keyword > build/fn-keyword.out
diff -u tests/expected-fn-keyword.txt build/fn-keyword.out

# The emit-mir CLI lowers, verifies, and prints the currently supported subset.
./build/ylang emit-mir tests/emit-mir.yl > build/emit-mir.out
diff -u tests/expected-emit-mir.txt build/emit-mir.out

# Unsupported functions fail before any partial MIR is written.
if ./build/ylang emit-mir tests/fn-keyword.yl > build/emit-mir-unsupported.out 2> build/emit-mir-unsupported.err; then
    echo "FAIL: emit-mir accepted a function outside the initial lowering subset" >&2
    exit 1
fi
test ! -s build/emit-mir-unsupported.out
grep -q "cannot lower function 'main'" build/emit-mir-unsupported.err

# emit-mir writes to stdout and does not accept an output path.
if ./build/ylang emit-mir tests/emit-mir.yl -o build/emit-mir.txt > build/emit-mir-argument.out 2>&1; then
    echo "FAIL: emit-mir accepted -o" >&2
    exit 1
fi
grep -q "emit-mir does not accept -o" build/emit-mir-argument.out

# Nested control flow and loop-carried scalar values are represented in verified MIR.
./build/ylang emit-mir tests/emit-mir-control-flow.yl > build/emit-mir-control-flow.out
grep -q 'cond_br' build/emit-mir-control-flow.out
grep -q 'br bb' build/emit-mir-control-flow.out
grep -Eq '^bb[0-9]+\(%[0-9]+: i64\):$' build/emit-mir-control-flow.out

# Direct user-function calls preserve typed parameters and return values in MIR.
./build/ylang emit-mir tests/emit-mir-calls.yl > build/emit-mir-calls.out
grep -Fq 'call @notify()' build/emit-mir-calls.out
grep -Fq 'call @identity(' build/emit-mir-calls.out
grep -Fq 'call @add(' build/emit-mir-calls.out

# Imported IR calls use module-qualified symbols, including transitive imports.
# Both imported modules intentionally define a function named transform().
./build/ylang emit-mir tests/ir-module-calls/main.yl > build/emit-mir-module-calls.out
[ "$(grep -c '^fn transform(' build/emit-mir-module-calls.out)" -eq 2 ]
[ "$(grep -c 'call @transform(' build/emit-mir-module-calls.out)" -eq 2 ]
grep -Fq 'call @forward(' build/emit-mir-module-calls.out
grep -Fq 'call @answer(' build/emit-mir-module-calls.out
grep -Fq 'call @leaf(' build/emit-mir-module-calls.out

# The IR-to-C emitter must link duplicate source names from separate modules correctly.
./build/ylang emit-ir-c tests/ir-module-calls/main.yl -o build/ir-module-calls.c >/dev/null
cc -std=c17 -Wall -Wextra -Wpedantic build/ir-module-calls.c -o build/test-ir-module-calls
set +e
./build/test-ir-module-calls
ir_module_calls_status=$?
set -e
[ "$ir_module_calls_status" -eq 84 ]

# Boolean and/or use control-flow edges so the right operand is truly short-circuited.
./build/ylang emit-mir tests/emit-ir-c-short-circuit.yl > build/emit-ir-c-short-circuit.mir
[ "$(grep -c 'cond_br' build/emit-ir-c-short-circuit.mir)" -ge 4 ]
./build/ylang emit-ir-c tests/emit-ir-c-short-circuit.yl -o build/emit-ir-c-short-circuit.c >/dev/null
grep -Fq 'yir_div_i64' build/emit-ir-c-short-circuit.c
cc -std=c17 -Wall -Wextra -Wpedantic build/emit-ir-c-short-circuit.c -o build/test-emit-ir-c-short-circuit
set +e
./build/test-emit-ir-c-short-circuit
short_circuit_status=$?
set -e
[ "$short_circuit_status" -eq 42 ]

# Emit standalone C from verified IR, compile it, and run the generated executable.
./build/ylang emit-ir-c tests/emit-ir-c.yl -o build/emit-ir-c.c > build/emit-ir-c.out
grep -Fq 'yir_add_i64' build/emit-ir-c.c
cc -std=c17 -Wall -Wextra -Wpedantic build/emit-ir-c.c -o build/test-emit-ir-c
set +e
./build/test-emit-ir-c
emit_ir_c_status=$?
set -e
[ "$emit_ir_c_status" -eq 42 ]

# Checked division, modulo, and general integer negation work in IR-generated C.
./build/ylang emit-ir-c tests/emit-ir-c-arithmetic.yl -o build/emit-ir-c-arithmetic.c > build/emit-ir-c-arithmetic.out
grep -Fq 'yir_div_i64' build/emit-ir-c-arithmetic.c
grep -Fq 'yir_mod_i64' build/emit-ir-c-arithmetic.c
grep -Fq 'yir_neg_i64' build/emit-ir-c-arithmetic.c
cc -std=c17 -Wall -Wextra -Wpedantic build/emit-ir-c-arithmetic.c -o build/test-emit-ir-c-arithmetic
set +e
./build/test-emit-ir-c-arithmetic
emit_ir_c_arithmetic_status=$?
set -e
[ "$emit_ir_c_arithmetic_status" -eq 8 ]

# Division by zero must retain YLang's checked runtime failure.
./build/ylang emit-ir-c tests/emit-ir-c-div-zero.yl -o build/emit-ir-c-div-zero.c >/dev/null
cc -std=c17 -Wall -Wextra -Wpedantic build/emit-ir-c-div-zero.c -o build/test-emit-ir-c-div-zero
set +e
./build/test-emit-ir-c-div-zero > build/emit-ir-c-div-zero.stdout 2> build/emit-ir-c-div-zero.stderr
emit_ir_c_div_zero_status=$?
set -e
[ "$emit_ir_c_div_zero_status" -eq 70 ]
grep -Fq 'YLang runtime error: integer division by zero' build/emit-ir-c-div-zero.stderr

# INT64_MIN / -1 must fail rather than invoking C undefined behavior.
./build/ylang emit-ir-c tests/emit-ir-c-div-overflow.yl -o build/emit-ir-c-div-overflow.c >/dev/null
cc -std=c17 -Wall -Wextra -Wpedantic build/emit-ir-c-div-overflow.c -o build/test-emit-ir-c-div-overflow
set +e
./build/test-emit-ir-c-div-overflow > build/emit-ir-c-div-overflow.stdout 2> build/emit-ir-c-div-overflow.stderr
emit_ir_c_div_overflow_status=$?
set -e
[ "$emit_ir_c_div_overflow_status" -eq 70 ]
grep -Fq 'YLang runtime error: integer overflow in division' build/emit-ir-c-div-overflow.stderr

# Negating INT64_MIN must retain the checked overflow diagnostic.
./build/ylang emit-ir-c tests/emit-ir-c-neg-overflow.yl -o build/emit-ir-c-neg-overflow.c >/dev/null
cc -std=c17 -Wall -Wextra -Wpedantic build/emit-ir-c-neg-overflow.c -o build/test-emit-ir-c-neg-overflow
set +e
./build/test-emit-ir-c-neg-overflow > build/emit-ir-c-neg-overflow.stdout 2> build/emit-ir-c-neg-overflow.stderr
emit_ir_c_neg_overflow_status=$?
set -e
[ "$emit_ir_c_neg_overflow_status" -eq 70 ]
grep -Fq 'YLang runtime error: integer overflow in negation' build/emit-ir-c-neg-overflow.stderr

# INT64_MIN % -1 is defined as zero by YLang's current runtime.
./build/ylang emit-ir-c tests/emit-ir-c-modulo-edge.yl -o build/emit-ir-c-modulo-edge.c >/dev/null
cc -std=c17 -Wall -Wextra -Wpedantic build/emit-ir-c-modulo-edge.c -o build/test-emit-ir-c-modulo-edge
./build/test-emit-ir-c-modulo-edge
[ "$?" -eq 0 ]

# emit-ir-c requires an explicit output path.
if ./build/ylang emit-ir-c tests/emit-ir-c.yl > build/emit-ir-c-no-output.out 2>&1; then
    echo "FAIL: emit-ir-c accepted a missing output path" >&2
    exit 1
fi
grep -q "emit-ir-c requires -o" build/emit-ir-c-no-output.out

# Explicit mut is the preferred 3.0 spelling; legacy mutable let remains compatible.
./build/ylang check tests/explicit-mut.yl >/dev/null
./build/ylang build tests/explicit-mut.yl -o build/test-explicit-mut >/dev/null
./build/test-explicit-mut > build/explicit-mut.out
diff -u tests/expected-explicit-mut.txt build/explicit-mut.out

./build/ylang check examples/demo.yl
./build/ylang build examples/demo.yl -o build/test-demo >/dev/null
./build/test-demo > build/test-demo.out
diff -u tests/expected-demo.txt build/test-demo.out

# Calls, arithmetic operands, struct initializers, and array initializers evaluate left to right.
./build/ylang check tests/evaluation-order.yl >/dev/null
./build/ylang build tests/evaluation-order.yl -o build/test-evaluation-order >/dev/null
./build/test-evaluation-order > build/evaluation-order.out
diff -u tests/expected-evaluation-order.txt build/evaluation-order.out

# Safe auto-fix: replace a common typo in code, but leave strings/comments alone.
./build/ylang fix tests/typo-print.yl -o build/typo-print-fixed.yl > build/fix.out 2> build/fix.err
grep -q "replaced 'pritn' with 'print'" build/fix.err
grep -q 'print(age);' build/typo-print-fixed.yl
grep -q 'The literal word pritn must remain unchanged.' build/typo-print-fixed.yl
grep -q 'pritn(age) inside a comment' build/typo-print-fixed.yl
grep -q 'pritn(age);' tests/typo-print.yl
./build/ylang check build/typo-print-fixed.yl >/dev/null
./build/ylang build build/typo-print-fixed.yl -o build/test-typo-print >/dev/null
./build/test-typo-print > build/test-typo-print.out
diff -u tests/expected-typo-print.txt build/test-typo-print.out

# Do not rewrite a deliberately declared function called pritn.
./build/ylang fix tests/declared-pritn.yl -o build/declared-pritn-fixed.yl > build/declared-fix.out 2>&1
cmp tests/declared-pritn.yl build/declared-pritn-fixed.yl

./build/ylang build examples/types.yl -o build/test-types >/dev/null
./build/test-types > build/test-types.out
diff -u tests/expected-types.txt build/test-types.out

./build/ylang build tests/int-min.yl -o build/test-int-min >/dev/null
./build/test-int-min > build/int-min.out
diff -u tests/expected-int-min.txt build/int-min.out

./build/ylang build examples/conditions.yl -o build/test-conditions >/dev/null
./build/test-conditions > build/test-conditions.out
diff -u tests/expected-conditions.txt build/test-conditions.out

./build/ylang check tests/branch-init.yl >/dev/null

# Definite initialization merges nested if/else paths, but not a one-sided assignment.
cat > build/branch-init-nested.yl <<'EOF'
function main() -> int {
    let int score;
    if (true) {
        if (false) {
            score = 10;
        } else {
            score = 20;
        }
    } else {
        score = 30;
    }
    print(score);
    return 0;
}
EOF
./build/ylang check build/branch-init-nested.yl >/dev/null

cat > build/branch-init-missing-else.yl <<'EOF'
function main() -> int {
    let int score;
    if (true) {
        score = 10;
    }
    print(score);
    return 0;
}
EOF
if ./build/ylang check build/branch-init-missing-else.yl > build/branch-init-missing-else.out 2>&1; then
    echo "FAIL: a variable assigned on only one if path was accepted" >&2
    exit 1
fi
grep -q 'E2021' build/branch-init-missing-else.out
if ./build/ylang check tests/type-error.yl > build/type-error.out 2>&1; then
    echo "FAIL: type-error.yl was accepted" >&2
    exit 1
fi
grep -q 'E2001' build/type-error.out
grep -q "Did you mean 'print(value);'" build/type-error.out
grep -q 'check failed with' build/type-error.out
if grep -q 'no executable was produced' build/type-error.out; then
    echo "FAIL: check reported a build-only message" >&2
    exit 1
fi

rm -f build/invalid-program
if ./build/ylang build tests/type-error.yl -o build/invalid-program > build/build-type-error.out 2>&1; then
    echo "FAIL: build accepted invalid source" >&2
    exit 1
fi
grep -q 'build failed with' build/build-type-error.out
grep -q 'no executable was produced' build/build-type-error.out
if [ -e build/invalid-program ]; then
    echo "FAIL: invalid source produced an executable" >&2
    exit 1
fi

if ./build/ylang check tests/const-assignment.yl > build/const-assignment.out 2>&1; then
    echo "FAIL: assignment to const was accepted" >&2
    exit 1
fi
grep -q 'E2022' build/const-assignment.out
grep -q "Keep 'const' and remove this assignment" build/const-assignment.out

if ./build/ylang check tests/missing-semicolon.yl > build/missing-semicolon.out 2>&1; then
    echo "FAIL: missing semicolon was accepted" >&2
    exit 1
fi
grep -q 'E1002' build/missing-semicolon.out
grep -q "missing ';' before this token" build/missing-semicolon.out

if ./build/ylang check tests/uninitialized.yl > build/uninitialized.out 2>&1; then
    echo "FAIL: uninitialized read was accepted" >&2
    exit 1
fi
grep -q 'E2021' build/uninitialized.out

./build/ylang build tests/div-zero.yl -o build/test-div-zero >/dev/null
set +e
./build/test-div-zero > build/div-zero.out 2>&1
status=$?
set -e
[ "$status" -eq 70 ]
grep -q 'integer division by zero' build/div-zero.out

./build/ylang build tests/overflow.yl -o build/test-overflow >/dev/null
set +e
./build/test-overflow > build/overflow.out 2>&1
status=$?
set -e
[ "$status" -eq 70 ]
grep -q 'integer overflow in addition' build/overflow.out

if command -v clang >/dev/null 2>&1; then
    ./build/ylang build examples/demo.yl -o build/test-demo-clang --cc clang >/dev/null
    ./build/test-demo-clang > build/test-demo-clang.out
    diff -u tests/expected-demo.txt build/test-demo-clang.out
fi


# Pure Game2D helpers currently share the SDL2-linked game2d module.
# Skip this integration test when the SDL2 development package is unavailable.
if command -v pkg-config >/dev/null 2>&1 && pkg-config --exists sdl2; then
    cat > build/game2d-collision.yl <<'EOF'
from game2d.yl import game2d_rects_overlap, game2d_point_in_rect;
function main() -> int {
    print(game2d_rects_overlap(0, 0, 10, 10, 5, 5, 10, 10));
    print(game2d_rects_overlap(0, 0, 10, 10, 10, 0, 4, 4));
    print(game2d_rects_overlap(0, 0, 0, 10, 5, 5, 10, 10));
    print(game2d_point_in_rect(5, 5, 0, 0, 10, 10));
    print(game2d_point_in_rect(10, 5, 0, 0, 10, 10));
    return 0;
}
EOF
    YLANG_PATH=stdlib ./build/ylang check build/game2d-collision.yl >/dev/null
    YLANG_PATH=stdlib ./build/ylang build build/game2d-collision.yl -o build/test-game2d-collision >/dev/null
    ./build/test-game2d-collision > build/game2d-collision.out
    printf 'true\nfalse\nfalse\ntrue\nfalse\n' > build/game2d-collision.expected
    diff -u build/game2d-collision.expected build/game2d-collision.out
else
    echo "SKIP: Game2D collision integration test requires SDL2 development files and pkg-config." >&2
fi

# Global negative literals and negative array elements must remain C constant expressions.
cat > build/global-negative-initializers.yl <<'EOF'
let int global_negative = -5;
let int global_minimum = -9223372036854775808;
let int values[] = [-1, -2];
function main() -> int {
    print(global_negative, global_minimum, values[0]);
    return 0;
}
EOF
./build/ylang check build/global-negative-initializers.yl >/dev/null
./build/ylang build build/global-negative-initializers.yl -o build/test-global-negative-initializers >/dev/null
./build/test-global-negative-initializers > build/global-negative-initializers.out
printf '%s\n' '-5 -9223372036854775808 -1' > build/global-negative-initializers.expected
diff -u build/global-negative-initializers.expected build/global-negative-initializers.out

# Struct equality is rejected by sema rather than passed to the generated-C compiler.
cat > build/struct-equality-error.yl <<'EOF'
struct Point { int x; int y; }
function main() -> int {
    let Point left = Point(1, 2);
    let Point right = Point(1, 2);
    if (left == right) { print("same"); }
    return 0;
}
EOF
if ./build/ylang check build/struct-equality-error.yl > build/struct-equality-error.out 2>&1; then
    echo "FAIL: struct equality should be rejected until structural equality is implemented" >&2
    exit 1
fi
grep -q 'E2036' build/struct-equality-error.out
grep -q 'Struct values do not support equality comparisons yet' build/struct-equality-error.out
if ./build/ylang build build/struct-equality-error.yl -o build/struct-equality-error > build/struct-equality-build.out 2>&1; then
    echo "FAIL: build accepted unsupported struct equality" >&2
    exit 1
fi
if grep -Eqi 'invalid operands|initializer element is not constant' build/struct-equality-build.out; then
    echo "FAIL: struct equality escaped semantic checking and failed in the C compiler" >&2
    cat build/struct-equality-build.out >&2
    exit 1
fi

# Enum type mismatch diagnostics should name the actual declared enum types.
cat > build/enum-type-mismatch.yl <<'EOF'
enum Direction { North, East }
enum Color { Red, Blue }
function main() -> int {
